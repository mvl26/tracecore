_ALIAS = re.compile(r"^\{([^}]+)\}$")


def _node(tokens, path):
	node = tokens
	for part in path.split("."):
		node = node[part]
	return node


def resolve(tokens, path):
	value = _node(tokens, path)["$value"]
	while isinstance(value, str) and _ALIAS.match(value):
		value = _node(tokens, _ALIAS.match(value).group(1))["$value"]
	return value


def _px(value):
	return "0" if value in ("0px", "0") else value


def css_value(value, kind):
	if kind == "fontFamily":
		return ",".join(f'"{name}"' if " " in name else name for name in value)
	if kind == "shadow":
		if value["blur"] == "0px" and value["offsetY"] == "0px":
			return "none"
		parts = [_px(value["offsetX"]), _px(value["offsetY"]), _px(value["blur"])]
		if value.get("spread") not in (None, "0px", "0"):
			parts.append(value["spread"])
		return " ".join([*parts, value["color"]])
	if kind == "cubicBezier":
		return "cubic-bezier({})".format(",".join(str(v) for v in value))
	return str(value)


def _leaves(node):
	for key, child in node.items():
		if key.startswith("$") or not isinstance(child, dict):
			continue
		if "$value" in child:
			yield key, child
		else:
			for sub_key, sub in _leaves(child):
				yield f"{key}.{sub_key}", sub


def root_vars(tokens):
	mapped = {path for _, path in COLOR_VARS}
	missing = [f"color.{key}" for key, _ in _leaves(tokens["color"]) if f"color.{key}" not in mapped]
	if missing:
		raise ValueError(f"Color tokens without a --tc-* name in COLOR_VARS: {missing}")

	result = [
		(name, css_value(resolve(tokens, path), _node(tokens, path)["$type"])) for name, path in COLOR_VARS
	]
	for group, prefix, renames in GROUP_VARS:
		for key, leaf in _leaves(_node(tokens, group)):
			value = resolve(tokens, f"{group}.{key}")
			result.append((prefix + renames.get(key, key), css_value(value, leaf["$type"])))
	return result


def surface_vars(tokens, surface, root):
	overrides = _node(tokens, f"surface-override.{surface}")
	decls = {}
	floor = None
	for key, leaf in _leaves(overrides):
		if leaf["$type"] == "string":
			continue
		if key == FONT_FLOOR:
			floor = int(leaf["$value"][:-2])
			continue
		if key not in SURFACE_VARS:
			raise ValueError(f"surface-override.{surface}.{key} has no mapping in SURFACE_VARS")
		for name in SURFACE_VARS[key]:
			decls[name] = leaf["$value"]
	if floor:
		for name, value in root:
			if name.startswith("--tc-fs-") and name not in decls and int(value[:-2]) < floor:
				decls[name] = f"{floor}px"
	order = {name: i for i, (name, _) in enumerate(root)}
	return sorted(decls.items(), key=lambda item: order.get(item[0], len(order)))


def _block(selector, decls):
	body = "".join(f"  {name}:{value};\n" for name, value in decls)
	return f"{selector}{{\n{body}}}\n"


def build(tokens):
	root = root_vars(tokens)
	parts = [HEADER, _block(":root", root)]
	for surface in SURFACES:
		decls = surface_vars(tokens, surface, root)
		if decls:
			parts.append(_block(f'[data-surface="{surface}"]', decls))
	parts.append(
		"@media (prefers-reduced-motion:reduce){\n"
		"  *,*::before,*::after{transition:none!important;animation:none!important}\n"
		"}\n"
	)
	parts.append(":focus-visible{outline:var(--tc-bw-focus) solid var(--tc-focus);outline-offset:2px}\n")
	theme = HEADER + _block(
		':root:not([data-theme="dark"])', [(frappe_var, f"var({tc})") for frappe_var, tc in FRAPPE_THEME]
	)
	return "".join(parts), theme


def outputs(tokens_css, theme_css):
	"""Các file sinh ra. ``tracecore.bundle.css`` ghép sẵn (không @import: plugin postcss của Frappe
	chép file ra thư mục tạm nên import tương đối hỏng); esbuild gắn hash → hết cache cũ khi deploy."""
	body = lambda css: css.split("\n", 1)[1]  # noqa: E731 — bỏ dòng HEADER trùng
	return {
		"tokens.css": tokens_css,
		"tracecore-theme.css": theme_css,
		"tracecore.bundle.css": HEADER + body(tokens_css) + body(theme_css),
	}


def main(argv=None):
	parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
	parser.add_argument("--tokens", default=DEFAULT_TOKENS)
	parser.add_argument("--out-dir", default=DEFAULT_OUT_DIR)
	parser.add_argument("--check", action="store_true", help="exit 1 if generated files are out of date")
	args = parser.parse_args(argv)

	with open(args.tokens, encoding="utf-8") as handle:
		tokens_css, theme_css = build(json.load(handle))

	status = 0
	for filename, content in outputs(tokens_css, theme_css).items():
		path = os.path.join(args.out_dir, filename)
		current = None
		if os.path.exists(path):
			with open(path, encoding="utf-8") as handle:
				current = handle.read()
		if current == content:
			continue
		if args.check:
			print(f"{path} is out of date: run python3 scripts/build_tokens.py", file=sys.stderr)
			status = 1
			continue
		os.makedirs(args.out_dir, exist_ok=True)
		with open(path, "w", encoding="utf-8") as handle:
			handle.write(content)
		print(f"wrote {path}")
	return status


if __name__ == "__main__":
	sys.exit(main())
